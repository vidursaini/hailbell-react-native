#!/usr/bin/env node
// Copies the native SDKs into this package, so the React Native module compiles the same Swift and
// Kotlin code that native apps use. Nothing is rewritten: the chat screen, push handling and session
// logic all come from sdk/swift and sdk/android.
//
//   node scripts/sync-native.mjs           copy (runs on `npm install` here and before `npm pack`)
//   node scripts/sync-native.mjs --check   exit 1 if the copies differ from the native SDKs
//
// The copies are git-ignored. Edit sdk/swift and sdk/android, never the copies.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sdk = path.resolve(pkg, '..');

/** [from (inside sdk/), to (inside this package)], each a folder copied whole or a single file. */
export const COPIES = [
  ['swift/Sources/Hailbell', 'ios/Vendor/Hailbell'],
  ['swift/Sources/HailbellNotificationService', 'plugin/vendor/HailbellNotificationService'],
  ['android/hailbell/src/main/java', 'android/src/vendor/java'],
  ['android/hailbell/src/main/res', 'android/src/vendor/res'],
  ['android/hailbell/src/main/AndroidManifest.xml', 'android/src/vendor/AndroidManifest.xml'],
  ['android/hailbell/consumer-rules.pro', 'android/src/vendor/consumer-rules.pro'],
];

function files(root) {
  if (!fs.existsSync(root)) return [];
  if (fs.statSync(root).isFile()) return [''];
  return fs
    .readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile() && e.name !== '.DS_Store')
    .map((e) => path.relative(root, path.join(e.parentPath, e.name)))
    .sort();
}

function digest() {
  const hash = createHash('sha256');
  for (const [from] of COPIES) {
    const root = path.join(sdk, from);
    for (const f of files(root)) {
      hash.update(`${from}/${f}\n`);
      hash.update(fs.readFileSync(path.join(root, f)));
    }
  }
  return hash.digest('hex').slice(0, 16);
}

function differences() {
  const out = [];
  for (const [from, to] of COPIES) {
    const a = path.join(sdk, from);
    const b = path.join(pkg, to);
    const left = files(a);
    const right = files(b);
    for (const f of new Set([...left, ...right])) {
      const fa = path.join(a, f);
      const fb = path.join(b, f);
      if (!fs.existsSync(fa) || !fs.existsSync(fb) || !fs.readFileSync(fa).equals(fs.readFileSync(fb))) {
        out.push(path.join(to, f));
      }
    }
  }
  return out;
}

/**
 * The Android SDK's runtime dependencies, read from its build.gradle.kts and written as Groovy for
 * android/build.gradle to apply, so the two can't drift apart.
 */
const GRADLE_KTS = 'android/hailbell/build.gradle.kts';
const GRADLE_DEPS = 'android/src/vendor/dependencies.gradle';

function dependenciesGradle() {
  const kts = fs.readFileSync(path.join(sdk, GRADLE_KTS), 'utf8');
  const platforms = Object.fromEntries([...kts.matchAll(/val (\w+) = platform\("([^"]+)"\)/g)].map((m) => [m[1], m[2]]));
  const lines = [];
  for (const m of kts.matchAll(/^\s*implementation\(([^)]*\)?)\)/gm)) {
    const arg = m[1].trim();
    if (platforms[arg]) lines.push(`  implementation platform("${platforms[arg]}")`);
    else if (/^"[^"]+"$/.test(arg)) lines.push(`  implementation ${arg}`);
    else throw new Error(`sync-native: can't read dependency ${arg} in ${GRADLE_KTS}`);
  }
  if (!lines.length) throw new Error(`sync-native: no dependencies found in ${GRADLE_KTS}`);
  return `// Generated by scripts/sync-native.mjs from sdk/${GRADLE_KTS}. Don't edit.\ndependencies {\n${lines.join('\n')}\n}\n`;
}

const sourcesPresent = COPIES.every(([from]) => fs.existsSync(path.join(sdk, from)));

if (process.argv.includes('--check')) {
  if (!sourcesPresent) {
    console.error('sync-native: sdk/swift and sdk/android are not next to this package.');
    process.exit(1);
  }
  const diff = differences();
  const deps = path.join(pkg, GRADLE_DEPS);
  if (!fs.existsSync(deps) || fs.readFileSync(deps, 'utf8') !== dependenciesGradle()) diff.push(GRADLE_DEPS);
  if (diff.length) {
    console.error(`sync-native: ${diff.length} file(s) differ from the native SDKs. Run npm run sync-native.\n  ${diff.join('\n  ')}`);
    process.exit(1);
  }
  console.log('sync-native: copies match the native SDKs.');
} else if (!sourcesPresent) {
  // Installed from a tarball: the copies came inside it.
  if (!fs.existsSync(path.join(pkg, 'ios/Vendor/Hailbell'))) {
    console.error('sync-native: no native SDK sources found and no copies in the package.');
    process.exit(1);
  }
} else {
  for (const [from, to] of COPIES) {
    const target = path.join(pkg, to);
    fs.rmSync(target, { recursive: true, force: true });
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.cpSync(path.join(sdk, from), target, { recursive: true });
  }
  fs.writeFileSync(path.join(pkg, GRADLE_DEPS), dependenciesGradle());
  let commit = '';
  try {
    commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: sdk, encoding: 'utf8' }).trim();
    const dirty = execFileSync('git', ['status', '--porcelain', '--', 'swift', 'android'], { cwd: sdk, encoding: 'utf8' });
    if (dirty.trim()) commit += ' with local changes';
  } catch {
    // Not a git checkout. The content digest still identifies the copy.
  }
  fs.writeFileSync(
    path.join(pkg, 'VENDORED_FROM'),
    `Copied from sdk/swift and sdk/android by scripts/sync-native.mjs.\ncontent: ${digest()}\n` + (commit ? `commit: ${commit}\n` : ''),
  );
  console.log(`sync-native: copied the native SDKs (content ${digest()}).`);
}
