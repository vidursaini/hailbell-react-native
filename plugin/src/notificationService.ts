import fs from 'fs';
import path from 'path';

import type { NotificationServiceOptions } from './options';

/** The Swift SDK's extension class, copied into the plugin by scripts/sync-native.mjs. */
export const VENDOR_DIR = path.join(__dirname, '..', 'vendor', 'HailbellNotificationService');

/** The extension's principal class. Its superclass does the work. */
export function serviceSource(options: NotificationServiceOptions): string {
  const group = options.appGroup
    ? `\n    override var appGroup: String? { ${JSON.stringify(options.appGroup)} }\n`
    : '';
  return `// Generated by the @hailbell/react-native config plugin. Changes are lost on the next prebuild.
import UserNotifications

/// Adds images and buttons to Hailbell pushes, counts their delivery and increments the badge.
/// Other pushes pass through untouched.
final class NotificationService: HailbellNotificationService {${group}}
`;
}

export function infoPlist(options: { version: string; buildNumber: string; baseUrl?: string }): string {
  const api = options.baseUrl
    ? `\n  <key>HailbellAPI</key>\n  <string>${escapeXml(options.baseUrl)}</string>`
    : '';
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleDevelopmentRegion</key>
  <string>$(DEVELOPMENT_LANGUAGE)</string>
  <key>CFBundleDisplayName</key>
  <string>$(PRODUCT_NAME)</string>
  <key>CFBundleExecutable</key>
  <string>$(EXECUTABLE_NAME)</string>
  <key>CFBundleIdentifier</key>
  <string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
  <key>CFBundleInfoDictionaryVersion</key>
  <string>6.0</string>
  <key>CFBundleName</key>
  <string>$(PRODUCT_NAME)</string>
  <key>CFBundlePackageType</key>
  <string>$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
  <key>CFBundleShortVersionString</key>
  <string>${escapeXml(options.version)}</string>
  <key>CFBundleVersion</key>
  <string>${escapeXml(options.buildNumber)}</string>
  <key>NSExtension</key>
  <dict>
    <key>NSExtensionPointIdentifier</key>
    <string>com.apple.usernotifications.service</string>
    <key>NSExtensionPrincipalClass</key>
    <string>$(PRODUCT_MODULE_NAME).NotificationService</string>
  </dict>${api}
</dict>
</plist>
`;
}

export function entitlementsPlist(appGroup: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>com.apple.security.application-groups</key>
  <array>
    <string>${escapeXml(appGroup)}</string>
  </array>
</dict>
</plist>
`;
}

function escapeXml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** The files in the extension's folder, as [name, contents]. */
export function extensionFiles(
  options: NotificationServiceOptions,
  app: { version: string; buildNumber: string; baseUrl?: string },
): [string, string | Buffer][] {
  const vendored = path.join(VENDOR_DIR, 'HailbellNotificationService.swift');
  if (!fs.existsSync(vendored)) {
    throw new Error(
      "@hailbell/react-native: the notification service code is missing from the package. Run `npm run sync-native` in sdk/react-native.",
    );
  }
  const files: [string, string | Buffer][] = [
    ['NotificationService.swift', serviceSource(options)],
    ['HailbellNotificationService.swift', fs.readFileSync(vendored)],
    ['PrivacyInfo.xcprivacy', fs.readFileSync(path.join(VENDOR_DIR, 'PrivacyInfo.xcprivacy'))],
    ['Info.plist', infoPlist(app)],
  ];
  if (options.appGroup) files.push([`${options.targetName}.entitlements`, entitlementsPlist(options.appGroup)]);
  return files;
}

// The `xcode` package's project object. Typed loosely: it has no type definitions of its own.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type XcodeProject = any;

const SOURCES = ['NotificationService.swift', 'HailbellNotificationService.swift'];

/** The xcode package writes new target names in quotes, so `pbxTargetByName` alone misses them. */
export function hasTarget(project: XcodeProject, name: string): boolean {
  const targets = project.pbxNativeTargetSection();
  return Object.keys(targets).some((key) => {
    const target = targets[key];
    return typeof target === 'object' && String(target.name).replace(/^"|"$/g, '') === name;
  });
}

/**
 * Names the phase that embeds the extension the way Xcode does, and moves it right after the app's
 * Resources phase. Placed after the "Bundle React Native code and images" script phase, Xcode 15 and
 * later can report a dependency cycle.
 */
function placeEmbedPhase(project: XcodeProject, product: string) {
  const app = project.getFirstTarget();
  const phases: { value: string; comment: string }[] = app.firstTarget.buildPhases;
  const copySection = project.hash.project.objects.PBXCopyFilesBuildPhase ?? {};
  const embed = phases.find((phase) => {
    const files: { comment?: string }[] = copySection[phase.value]?.files ?? [];
    return files.some((file) => file.comment?.startsWith(product));
  });
  if (!embed) return;
  const name = 'Embed Foundation Extensions';
  copySection[embed.value].name = `"${name}"`;
  copySection[`${embed.value}_comment`] = name;
  embed.comment = name;
  phases.splice(phases.indexOf(embed), 1);
  const resources = phases.findIndex((phase) => phase.comment === 'Resources');
  phases.splice(resources >= 0 ? resources + 1 : phases.length, 0, embed);
}
const RESOURCES = ['PrivacyInfo.xcprivacy'];

/**
 * Adds the extension target to the Xcode project: its group of files, its build phases and settings,
 * and the phase that embeds it in the app. Does nothing when the target is already there, so
 * `expo prebuild` can run again.
 */
export function addExtensionTarget(
  project: XcodeProject,
  options: NotificationServiceOptions,
  settings: { deploymentTarget: string; developmentTeam?: string; version: string; buildNumber: string },
): boolean {
  if (hasTarget(project, options.targetName)) return false;

  const objects = project.hash.project.objects;
  // The xcode package fails on projects that don't have these sections yet.
  objects.PBXTargetDependency = objects.PBXTargetDependency || {};
  objects.PBXContainerItemProxy = objects.PBXContainerItemProxy || {};

  const files = [...SOURCES, ...RESOURCES, 'Info.plist'];
  if (options.appGroup) files.push(`${options.targetName}.entitlements`);
  const group = project.addPbxGroup(files, options.targetName, options.targetName);
  const mainGroup = project.getFirstProject().firstProject.mainGroup;
  project.addToPbxGroup(group.uuid, mainGroup);

  const target = project.addTarget(options.targetName, 'app_extension', options.targetName, options.bundleIdentifier);
  placeEmbedPhase(project, `${options.targetName}.appex`);
  project.addBuildPhase(SOURCES, 'PBXSourcesBuildPhase', 'Sources', target.uuid);
  project.addBuildPhase(RESOURCES, 'PBXResourcesBuildPhase', 'Resources', target.uuid);
  project.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', target.uuid);

  const configurations = project.pbxXCBuildConfigurationSection();
  const list = project.pbxXCConfigurationList()[target.pbxNativeTarget.buildConfigurationList];
  const ids = new Set((list?.buildConfigurations ?? []).map((c: { value: string }) => c.value));
  for (const id of ids) {
    const build = configurations[id as string]?.buildSettings;
    if (!build) continue;
    Object.assign(build, {
      INFOPLIST_FILE: `${options.targetName}/Info.plist`,
      PRODUCT_NAME: '"$(TARGET_NAME)"',
      PRODUCT_BUNDLE_IDENTIFIER: `"${options.bundleIdentifier}"`,
      IPHONEOS_DEPLOYMENT_TARGET: settings.deploymentTarget,
      SWIFT_VERSION: '5.0',
      TARGETED_DEVICE_FAMILY: '"1,2"',
      CODE_SIGN_STYLE: 'Automatic',
      SKIP_INSTALL: 'YES',
      GENERATE_INFOPLIST_FILE: 'NO',
      CLANG_ENABLE_MODULES: 'YES',
      MARKETING_VERSION: settings.version,
      CURRENT_PROJECT_VERSION: settings.buildNumber,
      APPLICATION_EXTENSION_API_ONLY: 'YES',
    });
    if (options.appGroup) build.CODE_SIGN_ENTITLEMENTS = `${options.targetName}/${options.targetName}.entitlements`;
    if (settings.developmentTeam) build.DEVELOPMENT_TEAM = settings.developmentTeam;
  }
  return true;
}
